void delay(uint32_t time_ms)
{
#ifdef _USE_HW_RTOS
  if (xTaskGetSchedulerState() != taskSCHEDULER_NOT_STARTED)
  {
    osDelay(time_ms);
  }
  else
  {
    HAL_Delay(time_ms);
  }
#else
  HAL_Delay(time_ms);
#endif
}

